import 'reflect-metadata';
import {test,before,after} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {readFileSync} from 'node:fs';
import sharp from 'sharp';
import {Test} from '@nestjs/testing';
import type {NestExpressApplication} from '@nestjs/platform-express';
import {AppModule} from '../src/app.module.js';
import {GamesService} from '../src/games/service.js';
import {PrismaService} from '../src/database/prisma.service.js';
import {PresetsService} from '../src/presets/service.js';
import {configureApp} from '../src/http/configure.js';
import {readConfig} from '../src/config/env.js';
import {authHarness} from './support/auth-flow.js';
const config=readConfig(process.env),db=new PrismaService(config),service=new GamesService(db,new PresetsService(db));
const source=JSON.parse(readFileSync(new URL('./fixtures/native-export.judytik.json',import.meta.url),'utf8')).preset;
let app:NestExpressApplication,base:string,cover:Buffer;
before(async()=>{
 await db.onModuleInit();cover=await sharp({create:{width:40,height:40,channels:3,background:'#e31283'}}).webp().toBuffer();
 const m=await Test.createTestingModule({imports:[AppModule.register({...config,auth:authHarness(db).config})]}).compile();
 app=configureApp(m.createNestApplication<NestExpressApplication>({logger:false}));await app.listen(0,'127.0.0.1');base=await app.getUrl();
});
after(async()=>{await app?.close();await db.onModuleDestroy();});
test('atomic native import persists cover, source, version and audit under the restricted runtime role',async()=>{
 const requestId=randomUUID(),slug='file-'+randomUUID();
 const result=await service.importFile({slug,name:'เกมจากไฟล์',description:'รายละเอียด',platform:'pc',categoryId:null,status:'published'},source,cover,base,requestId);
 assert.equal(result.game.coverUrl,base+'/v1/games/'+result.game.id+'/cover');
 assert.equal(result.preset.isDefault,true);assert.equal(result.preset.format,'action-preset-v1');assert.deepEqual(result.preset.payload,source);
 assert.equal(result.preset.slug,'default');assert.equal(result.preset.name,source.name);
 assert.equal((await service.versions(result.game.id,result.preset.id)).items.length,1);
 assert.equal(await db.client.auditEvent.count({where:{requestId}}),2);
 const img=await fetch(result.game.coverUrl);assert.equal(img.status,200);assert.equal(img.headers.get('content-type'),'image/webp');assert.deepEqual(Buffer.from(await img.arrayBuffer()),cover);
 assert(!JSON.stringify(await service.list({},true)).includes(cover.toString('base64')));
 const h=authHarness(db),account=await h.signIn();const copy=await service.importPreset(account.session,result.game.id,result.preset.id,{},randomUUID());assert.deepEqual(copy.preset.actions,source.actions);
 await service.remove('game',result.game.id,'"1"',randomUUID());assert.equal((await fetch(result.game.coverUrl)).status,404);
 assert.equal((await fetch(base+'/v1/admin/games/'+result.game.id+'/cover',{headers:{authorization:'Bearer '+config.adminApiKey}})).status,200);
});
test('concurrent duplicate slug imports create exactly one complete game, and invalid category leaves no rows',async()=>{
 const fields={slug:'duplicate-'+randomUUID(),name:'G',description:'',platform:'pc',categoryId:null,status:'draft' as const};
 const results=await Promise.allSettled([1,2].map(()=>service.importFile(fields,source,cover,base,randomUUID())));
 assert.equal(results.filter(r=>r.status==='fulfilled').length,1);
 const rejected=results.find(r=>r.status==='rejected');assert.equal(rejected?.status==='rejected' && rejected.reason.code,'GAME_SLUG_OR_DEFAULT_CONFLICT');
 const row=await db.client.game.findUniqueOrThrow({where:{slug:fields.slug}});
 assert.equal(await db.client.gameCover.count({where:{gameId:row.id}}),1);assert.equal(await db.client.gamePreset.count({where:{gameId:row.id}}),1);
 assert.equal((await fetch(base+'/v1/games/'+row.id+'/cover')).status,404);
 const bad={...fields,slug:'bad-'+randomUUID(),categoryId:randomUUID()};
 await assert.rejects(service.importFile(bad,source,cover,base,randomUUID()),{code:'GAME_CATEGORY_UNAVAILABLE'});
 assert.equal(await db.client.game.count({where:{slug:bad.slug}}),0);
});
test('real multipart HTTP import preserves commands and reports unresolved media without executing them',async()=>{
 const media={kind:'sound',media:{bindingId:randomUUID(),displayName:'ding.mp3'}};
 const payload={...source,actions:source.actions.map((rule:any)=>({...rule,effects:[...rule.effects,media]}))};
 const form=new FormData();form.set('slug','http-'+randomUUID());form.set('name','HTTP เกม');form.set('status','published');
 form.set('presetFile',new Blob([JSON.stringify({format:'judytik-actions-preset',version:1,preset:payload})]),'export.judytik.json');
 form.set('coverFile',new Blob([new Uint8Array(cover)],{type:'image/webp'}),'cover.webp');
 const response=await fetch(base+'/v1/admin/games/import',{method:'POST',headers:{authorization:'Bearer '+config.adminApiKey},body:form});
 assert.equal(response.status,201);const result=await response.json();assert.equal(result.warnings.length,1);
 assert.deepEqual(result.preset.payload,payload);
 assert.deepEqual((await service.preset(result.game.id,result.preset.id)).payload,payload);
});
test('late audit failure rolls back game, cover, preset and version instead of leaving a partial import',async()=>{
 const slug='rollback-'+randomUUID();
 const before=await Promise.all([db.client.gameCover.count(),db.client.gamePreset.count(),db.client.gamePresetVersion.count()]);
 const failingDb={client:{$transaction:(run:any)=>db.client.$transaction(tx=>run(new Proxy(tx,{get(target,key){if(key==='auditEvent')return {create:async()=>{throw new Error('Injected audit failure');}};return Reflect.get(target,key);}})))}};
 const failing=new GamesService(failingDb as any,new PresetsService(db));
 await assert.rejects(failing.importFile({slug,name:'G',description:'',platform:'pc',categoryId:null,status:'draft'},source,cover,base,randomUUID()),/Injected audit failure/);
 assert.equal(await db.client.game.count({where:{slug}}),0);
 const after=await Promise.all([db.client.gameCover.count(),db.client.gamePreset.count(),db.client.gamePresetVersion.count()]);
 assert.deepEqual(after,before);
});
